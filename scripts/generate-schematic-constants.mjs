#!/usr/bin/env node
/**
 * Generates the schematic copy of the values that the library owns.
 *
 * Why this exists
 * ---------------
 * The schematics compile to CommonJS with `rootDir: "schematics"`, while the
 * library is built by ng-packagr from `src/` as ESM. A single source file cannot
 * belong to both, and TypeScript enforces it:
 *
 *     error TS6059: File '.../src/lib/types.ts' is not under 'rootDir' '.../schematics'
 *
 * So the shared values used to be copy-pasted with a "KEEP IN SYNC" comment,
 * which is a promise rather than a mechanism. This script is the mechanism: the
 * library is the source of truth, and the schematic copy is generated, so it
 * cannot drift. `src/schematics/generated-config.spec.ts` fails if it somehow
 * does (for example if someone edits the generated file by hand or forgets to
 * regenerate after changing the library).
 *
 * Values are read through the TypeScript compiler API rather than with regular
 * expressions, so the extraction does not break on formatting, comments, or
 * trailing commas.
 *
 * Run it directly, or let the `prebuild` hook of projects/ngx-theme-stack run it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const libRoot = resolve(repoRoot, 'projects/ngx-theme-stack');
const TYPES = resolve(libRoot, 'src/lib/types.ts');
const CONFIG = resolve(libRoot, 'src/lib/config/index.ts');
const OUTPUT = resolve(libRoot, 'schematics/ng-add/generated-config.ts');

// ── Extraction helpers over the TypeScript AST ────────────────────────────────

function parse(path) {
  return ts.createSourceFile(path, readFileSync(path, 'utf8'), ts.ScriptTarget.Latest, true);
}

/** Finds `export const NAME = <initializer>` and returns the initializer node. */
function findInitializer(sourceFile, name) {
  let found;
  const visit = (node) => {
    if (
      ts.isVariableDeclaration(node) &&
      ts.isIdentifier(node.name) &&
      node.name.text === name &&
      node.initializer
    ) {
      found = node.initializer;
      return;
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  if (!found) {
    throw new Error(`could not find "export const ${name}" in ${sourceFile.fileName}`);
  }
  return found;
}

function expectString(node, name) {
  if (!ts.isStringLiteral(node)) {
    throw new Error(`"${name}" must be a plain string literal to be generated`);
  }
  return node.text;
}

function expectStringArray(node, name) {
  if (!ts.isAsExpression(node) && !ts.isArrayLiteralExpression(node)) {
    throw new Error(`"${name}" must be a string array literal to be generated`);
  }
  const array = ts.isAsExpression(node) ? node.expression : node;
  if (!ts.isArrayLiteralExpression(array)) {
    throw new Error(`"${name}" must be an array literal to be generated`);
  }
  return array.elements.map((element, index) => {
    if (!ts.isStringLiteral(element)) {
      throw new Error(`"${name}[${index}]" must be a string literal to be generated`);
    }
    return element.text;
  });
}

function expectStringProperties(node, name, properties) {
  if (!ts.isObjectLiteralExpression(node)) {
    throw new Error(`"${name}" must be an object literal to be generated`);
  }
  const out = {};
  for (const property of properties) {
    const found = node.properties.find(
      (p) => ts.isPropertyAssignment(p) && ts.isIdentifier(p.name) && p.name.text === property,
    );
    if (!found) throw new Error(`"${name}.${property}" not found`);
    out[property] = expectString(found.initializer, `${name}.${property}`);
  }
  return out;
}

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const asConstArray = (values) => `[${values.map(quote).join(', ')}] as const`;

// ── Read the canonical values ────────────────────────────────────────────────

const types = parse(TYPES);
const config = parse(CONFIG);

const defaultThemes = expectStringArray(findInitializer(types, 'DEFAULT_THEMES'), 'DEFAULT_THEMES');
const colorSchemes = expectStringArray(
  findInitializer(types, 'NG_COLOR_SCHEMES'),
  'NG_COLOR_SCHEMES',
);
const themeNameSource = expectString(findInitializer(types, 'THEME_NAME_SOURCE'), 'THEME_NAME_SOURCE');
const defaults = expectStringProperties(findInitializer(config, 'DEFAULT_NG_CONFIG'), 'DEFAULT_NG_CONFIG', [
  'defaultTheme',
  'storageKey',
  'mode',
  'strategy',
]);

// ── Emit ─────────────────────────────────────────────────────────────────────

const contents = `/**
 * AUTO-GENERATED by scripts/generate-schematic-constants.mjs — DO NOT EDIT.
 *
 * Source of truth:
 *   - src/lib/types.ts        (DEFAULT_THEMES, NG_COLOR_SCHEMES, THEME_NAME_SOURCE)
 *   - src/lib/config/index.ts (DEFAULT_NG_CONFIG)
 *
 * The schematics compile to CommonJS with \`rootDir: "schematics"\` and cannot
 * import the ESM library, so the build copies these values here. Regenerate with
 * \`pnpm --filter ngx-theme-stack run generate:constants\` (also runs on prebuild).
 *
 * src/schematics/generated-config.spec.ts asserts these still match the library.
 */

export const DEFAULT_THEMES = ${asConstArray(defaultThemes)};

export const NG_COLOR_SCHEMES = ${asConstArray(colorSchemes)};

export const THEME_NAME_SOURCE = ${quote(themeNameSource)};

export const DEFAULT_NG_CONFIG = {
  defaultTheme: ${quote(defaults['defaultTheme'])},
  storageKey: ${quote(defaults['storageKey'])},
  mode: ${quote(defaults['mode'])},
  strategy: ${quote(defaults['strategy'])},
} as const;
`;

let previous = '';
try {
  previous = readFileSync(OUTPUT, 'utf8');
} catch {
  // first run
}

if (previous === contents) {
  console.log(`unchanged  ${relative(repoRoot, OUTPUT)}`);
} else {
  writeFileSync(OUTPUT, contents);
  console.log(`${previous ? 'updated  ' : 'created  '}${relative(repoRoot, OUTPUT)}`);
}
